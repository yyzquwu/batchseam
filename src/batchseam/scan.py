"""Read Python source for discovery without loading the scanned project."""

from io import BytesIO, StringIO, TextIOWrapper
from os.path import abspath
from pathlib import Path
import re
import stat
from tokenize import detect_encoding

from .discovery import discover

_SKIP_DIRS = frozenset("""
    .venv venv .env env .virtualenv virtualenv virtualenvs .virtualenvs .direnv
    .git .hg .svn .bzr CVS
    node_modules site-packages dist-packages __pypackages__ vendor vendored
    build dist _build .eggs __pycache__ .cache .pytest_cache .mypy_cache
    .ruff_cache .pytype .tox .nox .hypothesis
""".lower().split())
_REPRO_TEST = re.compile(r"test_batchseam_[0-9a-f]{32}\.py")
_GENERATED = re.compile(
    r"(?:@generated\b|<auto-generated\b|this is an? (?:auto[- ]?)?generated file\b"
    r"|(?:this (?:file|code) (?:is |was |has been )|code )?(?:automatically |auto[- ]?)?generated\b"
    r"(?:\s*(?:$|[.!:])|\s+(?:by|from|using|with|code|file)\b)"
    r"|do not edit(?: this file)?(?: manually)?(?:[.!:]|$))", re.IGNORECASE,
)
_LINE_END = re.compile(rb"\r\n?|\n")
_LINE = re.compile(rb"[^\r\n]*(?:\r\n?|\n|$)")


def _linked(info):
    return (stat.S_ISLNK(info.st_mode)
            or getattr(info, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT)


def _read_source(path):
    data = path.read_bytes()
    lines = _LINE.finditer(data)
    number = 0

    def readline():
        nonlocal number
        number += 1
        line = next(lines, None)
        return line[0] if line else b""

    try:
        encoding, _ = detect_encoding(readline)
    except SyntaxError as err:
        raise SyntaxError(f"line {number}: {err.msg}") from err
    try:
        with TextIOWrapper(BytesIO(data), encoding=encoding) as file:
            return file.read()
    except UnicodeDecodeError as err:
        prefix = _LINE_END.split(err.object[:err.start])
        raise SyntaxError(f"line {len(prefix)}, byte {len(prefix[-1]) + 1}: {err}") from err
    except (LookupError, UnicodeError) as err:
        raise SyntaxError(f"line {number}: {err}") from err


def _generated(path, source):
    if (path.name.casefold() == "test_regression.py" and "def test_batchseam_regression():" in source
            and "batchseam replay exited with" in source):
        return True
    for line in StringIO(source):
        line = line.strip(" \t\f\n")
        if line and not line.startswith("#"):
            break
        if line.startswith("#") and _GENERATED.match(line[1:].strip()):
            return True
    return False


def scan_tree(path: Path | str) -> dict:
    """Scan a directory or one Python file, counting source attempts including errors."""
    target = Path(path).absolute()
    display = Path(abspath(target))
    root = display.parent if display.suffix.casefold() == ".py" else display
    errors, findings = [], []
    report = dict(root=str(root), files_scanned=0, findings=findings, errors=errors)

    def error(entry, exc):
        if isinstance(exc, SyntaxError):
            message = exc.msg
            if exc.lineno:
                column = f", column {exc.offset}" if exc.offset else ""
                message = f"line {exc.lineno}{column}: {message}"
        else:
            message = getattr(exc, "strerror", None) or str(exc)
        errors.append(dict(path=entry.relative_to(root).as_posix(), message=message))

    try:
        # The caller selects the root. Its parents may be links (e.g. /tmp on macOS).
        target = target.parent.resolve() / target.name
        target_info = target.lstat()
    except (OSError, ValueError) as exc:
        error(display, exc)
        return report
    if _linked(target_info):
        error(display, ValueError("The scan root is a link. Select its target to scan it."))
        return report
    is_dir = stat.S_ISDIR(target_info.st_mode)
    root = target if is_dir else target.parent
    report["root"] = str(root)
    if not is_dir and (not stat.S_ISREG(target_info.st_mode) or target.suffix.casefold() != ".py"):
        error(target, ValueError("Expected a directory or a .py file"))
        return report

    pending = [target]
    while pending:
        entry = pending.pop()
        name = entry.name.casefold()
        if name in _SKIP_DIRS or name.endswith((".egg-info", ".dist-info")):
            continue
        try:
            info = target_info if entry == target else entry.lstat()
            if _linked(info):
                continue
            if stat.S_ISDIR(info.st_mode):
                children = list(entry.iterdir())
                if all(child.name.casefold() != "pyvenv.cfg" for child in children):
                    pending.extend(children)
            elif stat.S_ISREG(info.st_mode) and entry.suffix.casefold() == ".py" and not _REPRO_TEST.fullmatch(name):
                report["files_scanned"] += 1
                source = _read_source(entry)
                if _generated(entry, source):
                    report["files_scanned"] -= 1
                else:
                    findings.extend(discover(source, entry.relative_to(root).as_posix()))
        except (OSError, SyntaxError, UnicodeError, RecursionError) as exc:
            error(entry, exc)

    findings.sort(key=lambda finding: (finding["path"], finding["line"]))
    errors.sort(key=lambda item: item["path"])
    return report
