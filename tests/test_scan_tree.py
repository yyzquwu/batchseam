from pathlib import Path
import sys

import pytest

from batchseam.scan import scan_tree

SOURCE = 'import polars as pl\npl.col("x").map_batches(lambda values: values, is_elementwise=True)\n'


def _write(path, source=SOURCE):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source, encoding="utf-8")
    return path


def test_scan_reports_sorted_relative_paths_and_does_not_execute_source(tmp_path, monkeypatch):
    _write(tmp_path / "z.py", SOURCE * 2)
    _write(tmp_path / "a" / "nested.py")
    script = _write(tmp_path / "a.py", 'from pathlib import Path\nPath(__file__).with_name("executed").touch()\n' + SOURCE)
    _write(tmp_path / "ignore.txt")
    monkeypatch.chdir(tmp_path)

    report = scan_tree(".")
    assert report == scan_tree(tmp_path)
    assert report["root"] == str(tmp_path)
    assert report["files_scanned"] == 3
    assert report["errors"] == []
    assert [(row["path"], row["line"]) for row in report["findings"]] == [
        ("a.py", 4), ("a/nested.py", 2), ("z.py", 2), ("z.py", 4),
    ]
    assert scan_tree("a/../a.py") == dict(root=str(tmp_path), files_scanned=1, errors=[],
                                           findings=report["findings"][:1])
    assert scan_tree(script)["findings"] == report["findings"][:1]
    assert not (tmp_path / "executed").exists()


def test_scan_skips_environments_dependencies_build_caches_and_vcs(tmp_path):
    for name in (".VENV", "node_modules", "site-packages", "__pypackages__", "vendor", "build", "dist", ".git",
                 "lib.egg-info", "lib.dist-info", "__pycache__", ".ruff_cache", "renamed-env"):
        _write(tmp_path / name / "unexpected.py", "invalid syntax !!!")
    _write(tmp_path / "renamed-env" / "pyvenv.cfg", "home = elsewhere")
    _write(tmp_path / "project.py" / "test_batchseam.py")

    report = scan_tree(tmp_path)
    assert report["files_scanned"] == 1
    assert report["errors"] == []
    assert [row["path"] for row in report["findings"]] == ["project.py/test_batchseam.py"]
    assert scan_tree(tmp_path / "renamed-env")["files_scanned"] == 0
    assert scan_tree(tmp_path / "project.py")["root"] == str(tmp_path / "project.py")


def test_scan_skips_generated_source_and_old_and_new_repro_tests(tmp_path):
    markers = ("@generated", "Generated by protoc. DO NOT EDIT!", "<auto-generated>",
               "This file was automatically generated.", "Code generated by the build.",
               "This is a generated file.", "DO NOT EDIT THIS FILE MANUALLY.")
    for index, marker in enumerate(markers):
        _write(tmp_path / f"generated_{index}.py", f"#!/usr/bin/env python\n# {marker}\ninvalid syntax !!!")
    _write(tmp_path / ("test_batchseam_" + "a" * 32 + ".py"), "invalid syntax !!!")
    _write(tmp_path / "test_regression.py",
           SOURCE + 'def test_batchseam_regression():\n    return "batchseam replay exited with"\n')
    _write(tmp_path / "handwritten" / "test_regression.py", SOURCE + "# Generated by a user later.\n")

    report = scan_tree(tmp_path)
    assert report["files_scanned"] == 1
    assert report["errors"] == []
    assert [row["path"] for row in report["findings"]] == ["handwritten/test_regression.py"]


@pytest.mark.parametrize("newline", ["\n", "\r\n", "\r"])
def test_scan_honors_encoding_cookies_and_bom(tmp_path, newline):
    source = '#!/usr/bin/env python\n# coding: latin-1\n' + SOURCE.replace('"x"', '"caf\u00e9"')
    (tmp_path / "latin.py").write_bytes(source.replace("\n", newline).encode("latin-1"))
    (tmp_path / "utf8.py").write_bytes(SOURCE.encode("utf-8-sig"))

    report = scan_tree(tmp_path)
    assert report["files_scanned"] == 2
    assert report["errors"] == []
    assert [(row["path"], row["line"]) for row in report["findings"]] == [("latin.py", 4), ("utf8.py", 2)]
    assert "caf\u00e9" in report["findings"][0]["receiver"]


def test_scan_preserves_findings_and_reports_ordered_errors(tmp_path, monkeypatch):
    _write(tmp_path / "z_good.py")
    _write(tmp_path / "c_bad_syntax.py", "# comment\ndef invalid(:\n")
    _write(tmp_path / "b_bad_encoding.py", "# comment\n# coding: no-such-codec\n")
    (tmp_path / "a_bad_bytes.py").write_bytes(b"# coding: ascii\r\n# comment\r\n# \xff\r\n")
    blocked_file = _write(tmp_path / "d_unreadable.py")
    blocked_dir = _write(tmp_path / "e_unreadable" / "other.py").parent
    read_bytes, iterdir = Path.read_bytes, Path.iterdir

    def read(path):
        if path == blocked_file:
            raise PermissionError(13, "denied file", str(path))
        return read_bytes(path)

    def entries(path):
        if path == blocked_dir:
            raise PermissionError(13, "denied directory", str(path))
        return iterdir(path)

    monkeypatch.setattr(Path, "read_bytes", read)
    monkeypatch.setattr(Path, "iterdir", entries)
    report = scan_tree(tmp_path)

    assert report["files_scanned"] == 5
    assert [row["path"] for row in report["findings"]] == ["z_good.py"]
    assert [row["path"] for row in report["errors"]] == [
        "a_bad_bytes.py", "b_bad_encoding.py", "c_bad_syntax.py", "d_unreadable.py", "e_unreadable",
    ]
    messages = [row["message"] for row in report["errors"]]
    assert messages[0].startswith("line 3, byte 3:")
    assert messages[1].startswith("line 2: unknown encoding:")
    assert messages[2].startswith("line 2, column ")
    assert messages[3:] == ["denied file", "denied directory"]


def test_scan_reports_invalid_paths_and_accepts_empty_directories(tmp_path):
    assert scan_tree(tmp_path) == dict(root=str(tmp_path), files_scanned=0, findings=[], errors=[])
    missing = scan_tree(tmp_path / "missing.py")
    assert missing["root"] == str(tmp_path)
    assert [row["path"] for row in missing["errors"]] == ["missing.py"]
    wrong = scan_tree(_write(tmp_path / "source.txt"))
    assert wrong["root"] == str(tmp_path)
    assert wrong["errors"] == [dict(path="source.txt", message="Expected a directory or a .py file")]


def test_scan_skips_file_and_directory_symlinks(tmp_path):
    source = _write(tmp_path / "outside" / "hidden.py")
    root = tmp_path / "tree"
    root.mkdir()
    link = root / "file.py"
    try:
        link.symlink_to(source)
        (root / "dir").symlink_to(source.parent, target_is_directory=True)
        (root / "broken.py").symlink_to(root / "missing.py")
    except (OSError, NotImplementedError) as exc:
        pytest.skip(f"Cannot create symlinks: {exc}")

    assert scan_tree(root)["findings"] == []
    for path in (link, root / "dir"):
        assert scan_tree(path)["errors"][0]["message"].startswith("The scan root is a link")
    assert scan_tree(root / "dir" / source.name) == scan_tree(source)


@pytest.mark.skipif(sys.platform != "win32", reason="Junctions are Windows directory links")
def test_scan_skips_windows_junctions(tmp_path):
    import _winapi

    source = _write(tmp_path / "outside" / "hidden.py")
    root = tmp_path / "tree"
    root.mkdir()
    junction = root / "junction"
    _winapi.CreateJunction(str(source.parent), str(junction))

    assert scan_tree(root)["findings"] == []
    assert scan_tree(junction)["errors"][0]["message"].startswith("The scan root is a link")
    assert scan_tree(junction / source.name) == scan_tree(source)
